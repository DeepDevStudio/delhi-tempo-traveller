<h2 id="best-time">Best time for Char Dham Yatra</h2>
<p>The temples open around <strong>Akshaya Tritiya (April–May)</strong> and close around <strong>Diwali–Bhai Dooj (October–November)</strong>. The best windows are:</p>
<ul>
    <li><strong>May–June:</strong> pleasant weather, but the busiest period, so book the tempo and hotels early.</li>
    <li><strong>September–October:</strong> clear skies after the monsoon and fewer crowds. Our favourite window.</li>
    <li><strong>Avoid July–August:</strong> heavy rain and frequent landslides on mountain roads.</li>
</ul>

