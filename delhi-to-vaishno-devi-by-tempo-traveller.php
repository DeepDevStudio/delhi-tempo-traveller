<p>The yatra to <strong>Shri Mata Vaishno Devi</strong> in the Trikuta hills is one of the most important pilgrimages for families in North India. Travelling from Delhi by <strong>tempo traveller</strong> keeps the whole family together on the long road to Katra, with space for luggage, blankets and prasad.</p>

