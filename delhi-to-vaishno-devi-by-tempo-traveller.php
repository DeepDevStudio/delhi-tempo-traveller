<p>Most groups leave Delhi at night and reach Katra by morning, so the trek can start the same day.</p>

<h2 id="plan">Simple 3-day plan</h2>
<ul class="itinerary">
    <li><strong>Day 1: Delhi to Katra</strong>Overnight or early-morning drive on NH44. Check in at Katra and collect the yatra RFID card.</li>
    <li><strong>Day 2: Darshan</strong>Trek to the Bhawan (about 13 km) for Mata's darshan, then visit Bhairon Baba temple to complete the yatra.</li>
    <li><strong>Day 3: Katra to Delhi</strong>Rest in the morning and drive back to Delhi, with a lunch stop on the highway.</li>
</ul>

<h2 id="registration">Yatra registration</h2>
<p>Every pilgrim needs a <strong>yatra registration (RFID card)</strong>, which can be booked online on the Shri Mata Vaishno Devi Shrine Board website or collected at the counters in Katra. Carry a photo ID for every member of the group. Helicopter and Bhawan accommodation also have to be booked on the Shrine Board website, and they sell out early.</p>

